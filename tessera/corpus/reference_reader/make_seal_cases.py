"""
Generate ../seal-cases.json: the stored-manifest conformance vectors of SPEC §7 / ADR-0066.

Each case is a stored pair as a container holds it — `manifest` (the bytes of manifest.json, as a
string) and `seal` (the content of manifest.seal, or null when the member is missing) — with the
verdict every reader must reach (the Rust reader, tessera-core tests/seal_cases.rs; this directory's
run.py; tessera-wasm, natively and in Node) and the newer-field paths the Rust view reports.

Every case is derived from a corpus product in ../files (stored in the ADR-0066 layout) by one named
edit, so the file is reproducible: run it after an intended corpus change and review the diff.

    uv run --no-project --with blake3 --with jcs==0.2.1 python make_seal_cases.py

Spellings no JCS encoder emits (an integer beyond 2^53, NaN, `64.0`, a duplicate key, a BOM) are
written by injecting the raw token into the canonical bytes at a placeholder, so each case carries
exactly the one fault it names.
"""

from __future__ import annotations

import copy
import json
import os
import zipfile
from typing import Any, Callable

import blake3
import jcs

HERE = os.path.dirname(os.path.abspath(__file__))
CORPUS_DIR = os.path.dirname(HERE)
FILES_DIR = os.path.join(CORPUS_DIR, "files")
OUT = os.path.join(CORPUS_DIR, "seal-cases.json")

ABOUT = (
    "Stored-manifest seal cases (SPEC §4, §7; ADR-0066; #573, #901). Each case is a stored pair: "
    "'manifest' is the bytes of manifest.json and 'seal' the content of manifest.seal (null = the "
    "member is missing). Every reader reaches every verdict: the Rust reader (tessera-core "
    "tests/seal_cases.rs), the reference reader (reference_reader/run.py) and tessera-wasm "
    "(seal_verdict, natively and in Node), so they agree by construction. Verdicts, in ADR-0066 "
    "rule 4's order (a case with two faults has the verdict of the first): 'refused' = not read: no "
    "seal (the pre-ADR-0066 alpha layout, rule 10) or a seal that is not exactly 'blake3:' + 64 "
    "lower-case hex; not I-JSON (a duplicate key, NaN, a lone surrogate, nesting deeper than 127, a "
    "number beyond a double's range or whose value is an integer beyond ±(2^53−1) in any spelling, "
    "#886); not its own RFC 8785 JCS form (key order, whitespace, an escape or a number spelling JCS "
    "doesn't write, such as #901's sealed 64.0, a pretty layout); a 'manifest_hash' key in band; "
    "then, past the seal, a value in a form SPEC §5 doesn't declare (a record as an array, a block "
    "kind as an object, metadata: [], study: 5, a block kind or name outside its grammar), an "
    "unsupported major tessera_version, a block listed twice or without a digest. 'tampered' = the "
    "seal is not blake3 of the bytes, or id or content_hash doesn't match (a missing content_hash "
    "too). 'ok' = verifies. Families per corpus product: as-stored, newer-field-resealed (verifies, "
    "names the field), field-spliced (old seal), T4-T7 under the old seal and S7/S8 sealed by the "
    "attacker (the #897 spike's respellings), S5b (an exact double beyond 2^53, its own JCS form, "
    "refused by I-JSON), alpha-layout, seal-in-band-resealed. newer_fields = what the Rust view "
    "reports as not interpreted, each path rendered unambiguously (SPEC §4). Generated by "
    "reference_reader/make_seal_cases.py from corpus/files."
)


def digest(b: bytes) -> str:
    return "blake3:" + blake3.blake3(b).hexdigest()


def canon(v: Any) -> bytes:
    return jcs.canonicalize(v)


def inject(v: Any, tokens: dict[str, str]) -> bytes:
    """`canon(v)` with each string value `"<placeholder>"` replaced by its raw token."""
    out = canon(v).decode("utf-8")
    for placeholder, token in tokens.items():
        quoted = json.dumps(placeholder)
        assert out.count(quoted) == 1, placeholder
        out = out.replace(quoted, token)
    return out.encode("utf-8")


def merkle_root(digests: list[str]) -> str:
    """SPEC §3's MMR root, for the cases that recompute `content_hash`."""

    def leaf(d: str) -> bytes:
        return blake3.blake3(b"\x00" + d.encode()).digest()

    def node(a: bytes, b: bytes) -> bytes:
        return blake3.blake3(b"\x01" + a + b).digest()

    if not digests:
        return "blake3:" + blake3.blake3(b"").hexdigest()
    peaks: list[tuple[int, bytes]] = []
    for d in digests:
        h, height = leaf(d), 0
        while peaks and peaks[-1][0] == height:
            h = node(peaks.pop()[1], h)
            height += 1
        peaks.append((height, h))
    acc = peaks[-1][1]
    for _, p in reversed(peaks[:-1]):
        acc = node(p, acc)
    return "blake3:" + acc.hex()


def corpus() -> list[tuple[str, dict, bytes, str]]:
    """(name, object, stored bytes, seal) of every corpus product, in name order."""
    out = []
    for f in sorted(os.listdir(FILES_DIR)):
        if not f.endswith(".tsra"):
            continue
        with zipfile.ZipFile(os.path.join(FILES_DIR, f)) as zf:
            raw = zf.read("manifest.json")
            seal = zf.read("manifest.seal").decode("ascii")
        obj = json.loads(raw)
        assert canon(obj) == raw, f"{f}: not stored as its JCS form"
        assert digest(raw) == seal, f"{f}: manifest.seal is not blake3(manifest.json)"
        out.append((f[: -len(".tsra")], obj, raw, seal))
    return out


class Cases:
    def __init__(self) -> None:
        self.cases: list[dict] = []

    def add(
        self,
        name: str,
        verdict: str,
        manifest: bytes,
        seal: str | None,
        newer: list[str] | None = None,
    ) -> None:
        assert verdict in ("ok", "tampered", "refused"), verdict
        assert all(c["name"] != name for c in self.cases), name
        self.cases.append(
            {
                "name": name,
                "verdict": verdict,
                "newer_fields": newer or [],
                "manifest": manifest.decode("utf-8"),
                "seal": seal,
            }
        )

    def resealed(
        self, name: str, verdict: str, b: bytes, newer: list[str] | None = None
    ):
        """`b` sealed by its writer: the seal is the digest of exactly these bytes."""
        self.add(name, verdict, b, digest(b), newer)


def edited(obj: dict, edit: Callable[[dict], None]) -> dict:
    out = copy.deepcopy(obj)
    edit(out)
    return out


def set_key(key: str, value: Any) -> Callable[[dict], None]:
    def edit(m: dict) -> None:
        m[key] = value

    return edit


def respell_shape(text: str) -> tuple[str, int] | None:
    """The first number after `"shape":`, respelled as a float (`64` → `64.0`): T7/S7."""
    k = text.find('"shape"')
    if k < 0:
        return None
    start = k + next(i for i, c in enumerate(text[k:]) if c.isdigit())
    end = start + next(i for i, c in enumerate(text[start:]) if not c.isdigit())
    return text[:end] + ".0" + text[end:], end


def per_product(c: Cases, name: str, obj: dict, raw: bytes, seal: str) -> None:
    text = raw.decode("utf-8")
    c.add(f"{name}/as-stored", "ok", raw, seal)
    actors = [{"role": "implementer", "kind": "software_agent", "harness": "probe"}]
    c.resealed(
        f"{name}/newer-field-resealed",
        "ok",
        canon(edited(obj, set_key("actors", actors))),
        ["actors"],
    )
    c.add(
        f"{name}/field-spliced",
        "tampered",
        canon(edited(obj, set_key("forged", True))),
        seal,
    )
    # T4: the top-level members in reverse order, old seal.
    t4 = (
        "{"
        + ",".join(
            f"{json.dumps(k)}:{canon(v).decode()}" for k, v in reversed(obj.items())
        )
        + "}"
    )
    c.add(f"{name}/t4-keys-reordered", "refused", t4.encode(), seal)
    # T5: one space after the opening brace, old seal.
    c.add(f"{name}/t5-whitespace", "refused", ("{ " + text[1:]).encode(), seal)
    # T6: the first character of `tessera_version`'s value as a `\u` escape, old seal.
    q = text.index('"tessera_version":"') + len('"tessera_version":"')
    c.add(
        f"{name}/t6-unicode-escape",
        "refused",
        (text[:q] + f"\\u{ord(text[q]):04x}" + text[q + 1 :]).encode(),
        seal,
    )
    # T7 (old seal) and S7 (#901: sealed by the attacker): an array shape `64` written as `64.0`.
    shape = respell_shape(text)
    if shape:
        respelled = shape[0].encode()
        c.add(f"{name}/t7-shape-as-float", "refused", respelled, seal)
        c.resealed(f"{name}/s7-shape-as-float-resealed", "refused", respelled)
    # S5b: an exact double beyond 2^53 as a number, its own JCS form, sealed: refused by I-JSON.
    s5b = edited(
        obj, lambda m: m.setdefault("metadata", {}).update(daq_start_ns="@S5B@")
    )
    c.resealed(
        f"{name}/s5b-exact-double-beyond-2^53-resealed",
        "refused",
        inject(s5b, {"@S5B@": "1730000000123456800"}),
    )
    # S8: the pretty layout, sealed by the attacker.
    pretty = json.dumps(obj, indent=2, ensure_ascii=False).encode()
    c.resealed(f"{name}/s8-pretty-resealed", "refused", pretty)
    # The alpha layout (rule 10): pretty, the seal in band, no manifest.seal member.
    alpha = json.dumps(
        edited(obj, set_key("manifest_hash", seal)), indent=2, ensure_ascii=False
    )
    c.add(f"{name}/alpha-layout", "refused", alpha.encode(), None)
    # The seal in band, JCS, sealed over those very bytes.
    c.resealed(
        f"{name}/seal-in-band-resealed",
        "refused",
        canon(edited(obj, set_key("manifest_hash", seal))),
    )


def recon_int16(c: Cases, obj: dict, raw: bytes, seal: str, other_seal: str) -> None:
    """The typed-layer, I-JSON and seal-member cases, on one product."""
    p = "recon_int16"
    text = raw.decode("utf-8")

    def resealed(
        case: str, verdict: str, edit: Callable[[dict], None], newer=None
    ) -> None:
        c.resealed(f"{p}/{case}", verdict, canon(edited(obj, edit)), newer)

    def at_start(case: str, verdict: str, member: str) -> None:
        """`member` (raw text) spliced in as the first member of the top-level object, old seal."""
        c.add(f"{p}/{case}", verdict, ("{" + member + "," + text[1:]).encode(), seal)

    # The seal member itself.
    c.add(f"{p}/seal-member-missing", "refused", raw, None)
    c.add(f"{p}/seal-member-with-newline", "refused", raw, seal + "\n")
    c.add(
        f"{p}/seal-member-upper-case",
        "refused",
        raw,
        seal.upper().replace("BLAKE3:", "blake3:"),
    )
    c.add(f"{p}/seal-member-without-prefix", "refused", raw, seal[len("blake3:") :])
    c.add(f"{p}/seal-of-another-product", "tampered", raw, other_seal)

    # Encodings the typed view normalises or doesn't model, each sealed.
    resealed(
        "newer-field-empty-array-resealed", "ok", set_key("actors", []), ["actors"]
    )
    resealed(
        "nested-newer-field-resealed",
        "ok",
        lambda m: m["producer"].update(agents=["probe"]),
        ["producer.agents"],
    )

    def key_spelling(m: dict) -> None:
        m["producer"]["agents"] = ["probe"]
        m["producer.agents"] = ["probe"]

    resealed(
        "key-spelling-a-nested-path-resealed",
        "ok",
        key_spelling,
        ['["producer.agents"]', "producer.agents"],
    )
    resealed(
        "block-newer-field-resealed",
        "ok",
        lambda m: m["blocks"][0].update(stats={"min": -1024, "max": 3071.5}),
        ["blocks[0].stats"],
    )
    resealed("study-null-resealed", "ok", set_key("study", None))
    resealed("sources-omitted-resealed", "ok", lambda m: m.pop("sources"))
    resealed("ingest-transform-empty-resealed", "ok", set_key("ingest_transform", []))
    c.add(
        f"{p}/nested-field-spliced",
        "tampered",
        canon(edited(obj, lambda m: m["producer"].update(agents=["x"]))),
        seal,
    )
    resealed(
        "content-hash-deleted-resealed", "tampered", lambda m: m.pop("content_hash")
    )

    # Not I-JSON.
    at_start("duplicate-top-level-key", "refused", '"name":"forged"')
    at_start("duplicate-key-after-unescaping", "refused", '"n\\u0061me":"forged"')
    k = text.index('"id_inputs":{') + len('"id_inputs":{')
    c.add(
        f"{p}/duplicate-nested-key",
        "refused",
        (text[:k] + '"product":"forged",' + text[k:]).encode(),
        seal,
    )
    at_start("nan-constant", "refused", '"nan":NaN')
    c.add(
        f"{p}/lone-surrogate",
        "refused",
        canon(edited(obj, set_key("description", "@D@"))).replace(
            b'"@D@"', b'"\\ud800"'
        ),
        seal,
    )
    at_start("number-out-of-range", "refused", '"big":1e400')
    c.add(
        f"{p}/integer-out-of-range",
        "refused",
        inject(edited(obj, set_key("extra", {"x": "@X@"})), {"@X@": "1" + "0" * 190}),
        seal,
    )
    c.add(f"{p}/byte-order-mark", "refused", "﻿".encode() + raw, seal)

    def deep(levels: int) -> Callable[[dict], None]:
        def edit(m: dict) -> None:
            v: Any = []
            for _ in range(levels - 1):
                v = [v]
            m["extra"] = {"deep": v}

        return edit

    # The top-level object is 1 and `extra` 2, so 125 arrays nest 127 deep, 126 arrays 128 deep.
    resealed("nested-127-deep-resealed", "ok", deep(125))
    resealed("nested-128-deep-resealed", "refused", deep(126))

    # Integers beyond ±(2^53−1) in any spelling (#886), each resealed over its own bytes.
    def number_case(case: str, token: str, where: Callable[[dict], None]) -> None:
        c.resealed(f"{p}/{case}", "refused", inject(edited(obj, where), {"@N@": token}))

    daq = lambda m: m.setdefault("metadata", {}).update(daq_start_ns="@N@")  # noqa: E731
    for case, token in [
        ("integer-2^53-plus-1-resealed", "9007199254740993"),
        ("integer-below-minus-2^53-resealed", "-9007199254740993"),
        ("integer-with-zero-fraction-above-2^53-resealed", "9007199254740993.0"),
        ("integer-with-exponent-above-2^53-resealed", "9.007199254740993e15"),
        ("integer-1e300-resealed", "1e300"),
        ("integer-epoch-ns-resealed", "1730000000000000000"),
        ("fraction-lost-above-2^53-resealed", "9007199254740992.5"),
        ("fraction-rounding-to-2^53-resealed", "9007199254740991.5"),
    ]:
        number_case(case, token, daq)
    # Sealed as 2^53+1, served as 2^53: what a reader that rounds would see. Refused, never
    # verified under the seal of a different value.
    plus_one = inject(edited(obj, daq), {"@N@": "9007199254740993"})
    c.add(
        f"{p}/integer-2^53-plus-1-served-as-2^53",
        "refused",
        inject(edited(obj, daq), {"@N@": "9007199254740992"}),
        digest(plus_one),
    )
    number_case(
        "integer-above-2^53-in-generation-config-resealed",
        "9007199254740993",
        set_key("generation", {"config": {"seed": "@N@"}}),
    )
    # The numbers a double holds exactly verify, in their JCS spelling ...
    resealed(
        "numbers-a-double-holds-exactly-resealed",
        "ok",
        lambda m: m.setdefault("metadata", {}).update(
            max=9007199254740991, min=-9007199254740991, half=1.5, tiny=1e-300
        ),
    )
    # ... and are refused in any other: `9007199254740991.0` is I-JSON but not JCS (ADR-0066).
    c.resealed(
        f"{p}/number-a-double-holds-respelled-resealed",
        "refused",
        inject(edited(obj, daq), {"@N@": "9007199254740991.0"}),
    )

    # The typed layer, past the seal: forms SPEC §5 doesn't declare, each sealed.
    resealed("major-version-1-resealed", "refused", set_key("tessera_version", "1.0.0"))

    def listed_twice(m: dict) -> None:
        m["blocks"].append(copy.deepcopy(m["blocks"][0]))
        m["content_hash"] = merkle_root([b["digest"] for b in m["blocks"]])

    resealed("block-listed-twice", "refused", listed_twice)
    resealed(
        "block-array-form-resealed",
        "refused",
        lambda m: m.update(blocks=[list(m["blocks"][0].values())]),
    )
    resealed(
        "block-kind-object-form-resealed",
        "refused",
        lambda m: m["blocks"][0].update(kind={"array": None}),
    )
    resealed(
        "producer-array-form-resealed",
        "refused",
        lambda m: m.update(producer=[m["producer"]["tool"], m["producer"]["version"]]),
    )
    c.resealed(f"{p}/manifest-array-form", "refused", canon(list(obj.values())))
    resealed("metadata-array-resealed", "refused", set_key("metadata", []))
    resealed("extra-array-resealed", "refused", set_key("extra", []))
    resealed(
        "ingest-transform-params-array-resealed",
        "refused",
        set_key("ingest_transform", [{"name": "f16_widen", "params": []}]),
    )
    resealed(
        "generation-config-array-resealed",
        "refused",
        set_key("generation", {"config": []}),
    )
    resealed("id-inputs-array-resealed", "refused", set_key("id_inputs", []))
    resealed("study-number-resealed", "refused", set_key("study", 5))
    resealed(
        "tessera-version-number-resealed", "refused", set_key("tessera_version", 0)
    )
    resealed(
        "source-role-object-resealed",
        "refused",
        set_key("sources", [{"role": {"ingested_from": None}, "reference": "x"}]),
    )
    resealed(
        "producer-dirty-number-resealed",
        "refused",
        set_key("producer", {"tool": "t", "version": "1", "dirty": 1}),
    )
    resealed(
        "block-kind-capitalised-resealed",
        "refused",
        lambda m: m["blocks"][0].update(kind="Array"),
    )
    resealed(
        "block-kind-unknown-resealed",
        "refused",
        lambda m: m["blocks"][0].update(kind="hologram"),
    )
    resealed(
        "block-name-object-resealed",
        "refused",
        lambda m: m["blocks"][0].update(name={}),
    )
    resealed(
        "block-name-outside-grammar-resealed",
        "refused",
        lambda m: m["blocks"][0].update(name="has space"),
    )
    resealed(
        "block-digest-missing-resealed",
        "refused",
        lambda m: m["blocks"][0].pop("digest"),
    )


def main() -> None:
    products = corpus()
    assert len(products) == 8, [p[0] for p in products]
    c = Cases()
    for name, obj, raw, seal in products:
        per_product(c, name, obj, raw, seal)
    by_name = {p[0]: p for p in products}
    _, obj, raw, seal = by_name["recon_int16"]
    recon_int16(c, obj, raw, seal, by_name["recon_float32_mumap"][3])
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump({"about": ABOUT, "cases": c.cases}, f, indent=2, ensure_ascii=False)
        f.write("\n")
    print(f"wrote {len(c.cases)} cases to {OUT}")  # guardrails-ok: the script's report


if __name__ == "__main__":
    main()
