/// Every hazard from ADR-0056 §5 (plus §12a's H10/H11) that a **file-format fixture** can cover.
///
/// The exclusions are all deliberate, and each is a statement about reachability rather than about
/// effort — a hazard listed here that no fixture can actually fail for would be worse than an omission,
/// because `every_live_hazard_has_a_fixture` would then certify a blind spot:
///
/// - **H2** (lossy tile codecs — JPEG-in-TIFF and friends) is *rejected from the normalising path*
///   entirely, so there is nothing to seal and nothing to pin.
/// - **H5** (values under a NULL) is **unreachable through a file format**: Parquet stores no values
///   under its nulls (they are absent, encoded in the definition levels) and a CSV null is an empty
///   field. The hazard exists only at the in-memory arrow boundary, where a library consumer hands us a
///   `RecordBatch` built from a values buffer plus a separate mask — so it is covered by
///   `arrow_table::tests::garbage_under_a_null_is_zeroed_and_recorded` and
///   `canonical::tests::null_slots_are_zeroed_at_the_boundary`, which construct exactly that, and a
///   corpus fixture claiming it would be theatre.
/// - **H6** (NPY/raw endianness) belongs to the array lane.
/// - **H7** (SIMD-dispatched decode) is covered *through* H3/H4, exactly as the ADR's own table says.
pub const LIVE_HAZARDS: &[&str] = &["H1", "H3", "H4", "H8", "H9", "H10", "H11"];

/// The number of fixtures each named build configuration must run.
///
/// The anti-vacuity guard (ADR-0057 §5). Declared rather than derived on purpose: a count computed from
/// the same predicate the runner uses would agree with the runner by construction and prove nothing.
/// Every configuration named here must be one a build can actually *reach*, or the guard is decorative.
///
/// `--no-default-features` is deliberately **absent**: with no generic lane at all this module does not
/// compile (it needs an arrow writer to generate its sources), and `tests/ingest_corpus.rs` is
/// `#![cfg]`-skipped there. That is not the blind spot the guard exists to close — a corpus that does not
/// build is loud, while a corpus that builds and silently runs three of nine fixtures is not.
pub const EXPECTED_COUNTS: &[(&str, usize)] = &[
    // `default` = arrow + parquet + csv, which is every generic lane P1 ships.
    ("default", 9),
    // `full` and `--all-features` add vendor decoders and the `sql`/`cloud` surfaces; neither adds a
    // generic lane, so the count is unchanged. That invariance is itself the claim: a feature may
    // decide whether a format is readable, never how one encodes.
    ("full", 9),
    ("all-features", 9),
    // `--no-default-features --features parquet` — a real configuration for an embedder who wants the
    // columnar lane without the text one. The two CSV fixtures drop out, and the count says so, which
    // is exactly the case that would otherwise pass while quietly testing less.
    ("parquet-no-csv", 7),
];

/// The committed golden record for one fixture.
///
/// Carries `ingest_decoder` (ADR-0056 §6a's gate requires it, and it lands *with* the first fixture, not
/// after) so a reviewer can tell a decoder bump from a semantic change by reading the diff: a
/// `manifest_hash` that moved next to an `ingest_decoder` that moved is routine; one without is not.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct IngestGolden {
    pub name: String,
    pub product: String,
    /// Cargo features this fixture needs.
    pub requires: Vec<String>,
    /// ADR-0056 §5 hazards this fixture is the coverage for.
    pub hazards: Vec<String>,
    pub id: String,
    pub content_hash: String,
    pub manifest_hash: String,
    /// The sealed decoder triple, lifted out of the recipe bag for reviewability.
    pub ingest_decoder: serde_json::Value,
}

/// The committed corpus file: the declared counts plus one golden per fixture.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct IngestCorpus {
    /// Expected fixture count per named configuration — the anti-vacuity guard.
    pub expected_counts: std::collections::BTreeMap<String, usize>,
    pub fixtures: Vec<IngestGolden>,
}

/// One corpus fixture: how to write its source file, and how to ingest what was written.
pub struct IngestFixture {
    pub name: &'static str,
    /// Cargo features required for this fixture to run at all.
    pub requires: &'static [&'static str],
    /// ADR-0056 §5 hazards this fixture pins.
    pub hazards: &'static [&'static str],
    /// Write the source file into `dir`, returning its path.
    pub build: fn(&Path) -> Result<PathBuf>,
    /// The ingest options for that source file.
    pub options: fn(PathBuf) -> FormatOptions,
}

fn he(e: impl std::fmt::Display) -> Error {
    Error::Invalid(format!("ingest-corpus: {e}"))
}

/// A fixed timestamp. Identity is content-derived, so a corpus fixture must never see a clock.
const TS: &str = "2024-01-01T00:00:00Z";

/// A fixed `ingested_from` label. The generated source lives in a temp dir whose path differs every
/// run, and the path would otherwise land in the sealed edge and move `manifest_hash` per run.
const LABEL: &str = "corpus/ingest";

/// Every fixture, in a fixed order (the corpus file is compared element-wise).
pub fn fixtures() -> Vec<IngestFixture> {
    vec![
        IngestFixture {
            name: "ingest_parquet_scalars",
            requires: &["parquet"],
            // H11 too: sixteen columns of distinct widths in a fixed order, so a re-encode that sorted
            // them or widened an `Int8` to the machine word would move this fixture.
            hazards: &["H1", "H9", "H11"],
            build: write_scalars,
            options: parquet_opts,
        },
        IngestFixture {
            name: "ingest_parquet_nulls",
            requires: &["parquet"],
            // H10, not H5: what a Parquet round-trip can pin is **nullability-by-presence** — a column
            // declared nullable that contains no null must come out unwrapped, and one that contains a
            // null must come out masked. H5 (producer garbage *under* a null) cannot be expressed in a
            // Parquet file at all; see LIVE_HAZARDS.
            hazards: &["H10"],
            build: write_nulls,
            options: parquet_opts,
        },
        IngestFixture {
            name: "ingest_parquet_floats",
            requires: &["parquet"],
            hazards: &["H4"],
            build: write_floats,
            options: parquet_opts,
        },
        IngestFixture {
            name: "ingest_parquet_dictionary",
            requires: &["parquet"],
            hazards: &["H9"],
            build: write_dictionary,
            options: parquet_opts,
        },
        IngestFixture {
            name: "ingest_parquet_plain_strings",
            requires: &["parquet"],
            hazards: &["H9"],
            build: write_plain_strings,
            options: parquet_opts,
        },
        IngestFixture {
            name: "ingest_parquet_tiny_row_groups",
            requires: &["parquet"],
            hazards: &["H9"],
            build: write_tiny_row_groups,
            options: parquet_opts,
        },
        IngestFixture {
            name: "ingest_arrow_ipc_scalars",
            requires: &["arrow"],
            hazards: &["H9"],
            build: write_arrow_ipc,
            options: arrow_opts,
        },
        IngestFixture {
            name: "ingest_csv_declared",
            requires: &["csv"],
            hazards: &["H3", "H8"],
            build: write_csv,
            options: csv_opts,
        },
        IngestFixture {
            name: "ingest_csv_nulls",
            requires: &["csv"],
            hazards: &["H10"],
            build: write_csv_nulls,
            options: csv_nulls_opts,
        },
    ]
}

/// Whether a fixture can run in *this* build.
pub fn enabled(f: &IngestFixture) -> bool {
    f.requires.iter().all(|r| match *r {
        "arrow" => cfg!(feature = "arrow"),
        "parquet" => cfg!(feature = "parquet"),
        "csv" => cfg!(feature = "csv"),
        // An unknown predicate must not silently enable a fixture.
        _ => false,
    })
}

/// The fixtures enabled in this build, in corpus order.
pub fn enabled_fixtures() -> Vec<IngestFixture> {
    fixtures().into_iter().filter(enabled).collect()
}

/// Build + ingest one fixture and return its golden record.
///
/// Goes through the ingest **seam** ([`crate::engine::decode_generic_table`] +
/// [`crate::canonical::to_table_product`]) rather than through `engine::run`, and that is a
/// determinism requirement rather than a shortcut. `engine::run` seals an `ingested_via_spec` edge
/// whose digest is over the *parsed spec*, and a spec names its `input` **path** — which for a
/// generated fixture is a temp directory that differs on every run. Sealing it would make
/// `manifest_hash` unreproducible and the §6a value-preservation check unenforceable.
///
/// What is left is exactly the ingest: the source digest, the decoder triple, the transform receipt,
/// the schema and the payload. The spec-engine path is covered by `tests/generic_table.rs` instead.
pub fn golden(f: &IngestFixture, dir: &Path) -> Result<IngestGolden> {
    let input = (f.build)(dir)?;
    let options = (f.options)(input.clone());
    let (table, source_format, decoder) = crate::engine::decode_generic_table(&options)?
        .ok_or_else(|| he(format!("fixture '{}' is not a generic backend", f.name)))?;
    let (m, _payloads) = crate::canonical::to_table_product(
        &table,
        &crate::canonical::GenericIngest {
            name: f.name,
            timestamp: TS,
            description: "ingest conformance fixture",
            source_format,
            source_path: &input,
            // The generated source lives in a temp dir whose path differs every run; the label is what
            // keeps the sealed `ingested_from` reference stable. (ADR-0040 wants this for PHI hygiene
            // anyway — here it is also what makes the golden reproducible.)
            source_label: Some(LABEL),
            extra_sources: &[],
            decoder,
            generation: None,
            column_meta: &crate::column_meta::ColumnMeta::empty(),
        },
    )?;
    Ok(record(f, &m))
}

/// Project a sealed manifest into its golden record.
fn record(f: &IngestFixture, m: &Manifest) -> IngestGolden {
    IngestGolden {
        name: f.name.into(),
        product: m.product.clone(),
        requires: f.requires.iter().map(|s| s.to_string()).collect(),
        hazards: f.hazards.iter().map(|s| s.to_string()).collect(),
        id: m.id.clone(),
        content_hash: m.content_hash.clone().unwrap_or_default(),
        manifest_hash: m.manifest_hash.clone().unwrap_or_default(),
        ingest_decoder: m
            .generation
            .as_ref()
            .and_then(|g| g.config.get(crate::decoder::RECIPE_KEY))
            .cloned()
            .unwrap_or(serde_json::Value::Null),
    }
}

/// Build the whole corpus for this build configuration.
pub fn build(dir: &Path) -> Result<IngestCorpus> {
    let fixtures = enabled_fixtures();
    let mut out = Vec::with_capacity(fixtures.len());
    for f in &fixtures {
        out.push(golden(f, dir)?);
    }
    Ok(IngestCorpus {
        expected_counts: EXPECTED_COUNTS
            .iter()
            .map(|(k, v)| (k.to_string(), *v))
            .collect(),
        fixtures: out,
    })
}

