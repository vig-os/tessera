//! The **ingest conformance corpus** (ADR-0056 §5, ADR-0057 §5) — generic-ingest fixtures whose golden
//! hashes are pinned in `tessera/corpus/ingest-corpus.json`.
//!
//! # Why this exists separately from `tessera-io`'s corpus
//!
//! The existing seal corpus lives in `tessera-io`, which has **no decoders**, so it is feature-invariant
//! by construction. These fixtures need a decoder, so the corpus becomes feature-*conditional* — and a
//! feature-conditional corpus is exactly the shape that passes vacuously. This repo has already shipped
//! that failure: the trycmd docs-as-tests ran **zero cases** in CI for a period, because the `.trycmd`
//! files were not in the crane source filter, and a zero-case pass is indistinguishable from a green
//! run.
//!
//! So [`EXPECTED_COUNTS`] is a **declared count per named configuration**, and the test asserts the
//! count *before* comparing any hash. A `full` build that expects nine fixtures and runs three fails
//! loudly instead of passing quietly.
//!
//! # Source files are generated, never committed
//!
//! ADR-0056 §5 is explicit: the *source* files are generated at build time by a pinned writer, and only
//! the generator descriptor and the resulting golden hashes are committed. Committing binary Parquet
//! would bloat the repo and force golden churn on unrelated dependency bumps. Each fixture here is
//! therefore a `build` function plus the options to ingest what it wrote.
//!
//! The generated file's bytes need no determinism of their own — which is worth stating, because it
//! looks like a gap and is not. `content_hash` is over *our* encoded payload, so it is a function of the
//! extracted logical values only (ADR-0056 §6a Finding 1). `manifest_hash` *is* a function of the
//! generated bytes, via the `ingested_from` source digest, and arrow-rs stamps its own version into a
//! Parquet footer — so a `parquet` bump moves `manifest_hash` and must not move `content_hash`. That is
//! not incidental: it is precisely the §6a value-preservation check, made mechanical.
//!
//! # Hazard coverage
//!
//! ADR-0057 §5's anti-vacuity guard asks for "at least one fixture per live hazard H1–H9". Each fixture
//! declares which it covers in [`IngestFixture::hazards`], and
//! `tests/ingest_corpus.rs::every_live_hazard_has_a_fixture` checks the union — so a hazard cannot
//! quietly lose its coverage when a fixture is edited.

