fn parquet_opts(input: PathBuf) -> FormatOptions {
    FormatOptions::Parquet {
        input,
        exclude: Vec::new(),
        column_meta: Default::default(),
    }
}

fn arrow_opts(input: PathBuf) -> FormatOptions {
    FormatOptions::Arrow {
        input,
        exclude: Vec::new(),
        column_meta: Default::default(),
    }
}

fn csv_opts(input: PathBuf) -> FormatOptions {
    FormatOptions::Csv {
        input,
        columns: vec!["id:i4".into(), "x:f8".into(), "label:str".into()],
        delimiter: None,
        header: true,
        null_tokens: Vec::new(),
        exclude: Vec::new(),
        column_meta: Default::default(),
    }
}

fn csv_nulls_opts(input: PathBuf) -> FormatOptions {
    FormatOptions::Csv {
        input,
        columns: vec!["id:i4".into(), "x:f8?".into()],
        delimiter: None,
        header: true,
        null_tokens: vec!["NA".into()],
        exclude: Vec::new(),
        column_meta: Default::default(),
    }
}

/// Write a `RecordBatch` to Parquet with the given writer properties.
fn write_parquet_with(
    dir: &Path,
    name: &str,
    batch: &RecordBatch,
    props: parquet::file::properties::WriterProperties,
) -> Result<PathBuf> {
    let path = dir.join(format!("{name}.parquet"));
    let file = std::fs::File::create(&path).map_err(he)?;
    let mut w = parquet::arrow::ArrowWriter::try_new(file, batch.schema(), Some(props))
        .map_err(|e| he(format!("{name}: {e}")))?;
    w.write(batch).map_err(|e| he(format!("{name}: {e}")))?;
    w.close().map_err(|e| he(format!("{name}: {e}")))?;
    Ok(path)
}

fn field(name: &str, dt: DataType, nullable: bool) -> Field {
    Field::new(name, dt, nullable)
}

/// **H1 + H9** — every accepted scalar type in one table, including the two that carry the timezone
/// hazard (`timestamp(us, None)` and `timestamp(us, "America/New_York")`) and the two that carry a
/// recorded transform (`date32`, `decimal128(18,4)`).
///
/// The tz pair is the fixture that matters most: arrow stores UTC-normalised ticks and the zone is a
/// display annotation, so a decoder that "helpfully" applied a tzdb offset would move this fixture's
/// `content_hash` and nothing else in the suite would notice.
fn write_scalars(dir: &Path) -> Result<PathBuf> {
    let ticks = 1_704_067_200_000_000_i64; // 2024-01-01T00:00:00Z
    let schema = Arc::new(Schema::new(vec![
        field("i8", DataType::Int8, false),
        field("i16", DataType::Int16, false),
        field("i32", DataType::Int32, false),
        field("i64", DataType::Int64, false),
        field("u8", DataType::UInt8, false),
        field("u16", DataType::UInt16, false),
        field("u32", DataType::UInt32, false),
        field("u64", DataType::UInt64, false),
        field("f32", DataType::Float32, false),
        field("f64", DataType::Float64, false),
        field("boolean", DataType::Boolean, false),
        field("text", DataType::Utf8, false),
        field("day", DataType::Date32, false),
        field(
            "naive_ts",
            DataType::Timestamp(arrow_schema::TimeUnit::Microsecond, None),
            false,
        ),
        field(
            "zoned_ts",
            DataType::Timestamp(
                arrow_schema::TimeUnit::Microsecond,
                Some("America/New_York".into()),
            ),
            false,
        ),
        field("amount", DataType::Decimal128(18, 4), false),
    ]));
    let columns: Vec<ArrayRef> = vec![
        Arc::new(Int8Array::from(vec![-128, 0, 127])),
        Arc::new(Int16Array::from(vec![-32768, 0, 32767])),
        Arc::new(Int32Array::from(vec![i32::MIN, 0, i32::MAX])),
        // NOT `[i64::MIN, 0, i64::MAX]`. That shape — a full-width span containing zero — hits #468:
        // vortex 0.75.0 writes different container metadata for it under a debug vs a release build
        // (and x86-64 vs aarch64 release disagree), so the sealed bytes would be a function of the
        // compiler rather than of the data. ±(2^53 + 1) keeps what this column is *for* — a value no
        // `f64` can represent, so an i64 silently routed through a float is still caught — without
        // the pathological span. The pathological shape itself is covered, and its divergence pinned,
        // by `known_limitation_468_full_span_int_container_bytes`.
        Arc::new(Int64Array::from(vec![
            -9_007_199_254_740_993,
            0,
            9_007_199_254_740_993,
        ])),
        Arc::new(UInt8Array::from(vec![0u8, 1, 255])),
        Arc::new(UInt16Array::from(vec![0u16, 1, 65535])),
        Arc::new(UInt32Array::from(vec![0u32, 1, u32::MAX])),
        Arc::new(UInt64Array::from(vec![0u64, 1, u64::MAX])),
        Arc::new(Float32Array::from(vec![-1.5f32, 0.0, 3.25])),
        Arc::new(Float64Array::from(vec![-1.5f64, 0.0, 3.25])),
        Arc::new(BooleanArray::from(vec![true, false, true])),
        Arc::new(StringArray::from(vec!["alpha", "", "ωμέγα"])),
        Arc::new(Date32Array::from(vec![0, 19723, -1])),
        Arc::new(TimestampMicrosecondArray::from(vec![0, ticks, -1])),
        Arc::new(
            TimestampMicrosecondArray::from(vec![0, ticks, -1]).with_timezone("America/New_York"),
        ),
        Arc::new(
            Decimal128Array::from(vec![-1_234_567_i128, 0, 999_999_999_999_999_999_i128])
                .with_precision_and_scale(18, 4)
                .map_err(he)?,
        ),
    ];
    let batch = RecordBatch::try_new(schema, columns).map_err(he)?;
    write_parquet_with(
        dir,
        "scalars",
        &batch,
        parquet::file::properties::WriterProperties::builder().build(),
    )
}

/// **H5** — a nullable column with deliberate garbage under the null.
///
/// Arrow keeps whatever a producer left in a masked slot, so the fixture constructs the arrays by hand
/// (from an `Option` iterator arrow would write zeros) and the seal must be independent of it.
fn write_nulls(dir: &Path) -> Result<PathBuf> {
    let schema = Arc::new(Schema::new(vec![
        field("id", DataType::Int32, false),
        field("maybe_i64", DataType::Int64, true),
        field("maybe_f64", DataType::Float64, true),
        // Declared nullable, contains no null. The H10 half that is easy to get wrong: this column must
        // seal **unwrapped**, because pyarrow, polars and DuckDB disagree about the declaration and
        // honouring it would seal one logical table three ways.
        field("declared_nullable_but_full", DataType::Int32, true),
    ]));
    // Numeric only, deliberately: the table backend carries a validity mask for the fixed-width
    // numeric dtypes only, so a nullable `str` column is rejected at the boundary (with its own unit
    // test in `canonical.rs`) rather than sealed. Extending the mask to `str`/`b1` is an encoder
    // change tracked separately.
    let columns: Vec<ArrayRef> = vec![
        Arc::new(Int32Array::from(vec![1, 2, 3])),
        Arc::new(Int64Array::from(vec![Some(1), None, Some(3)])),
        Arc::new(Float64Array::from(vec![Some(1.5), None, Some(-0.0)])),
        Arc::new(Int32Array::from(vec![Some(4), Some(5), Some(6)])),
    ];
    let batch = RecordBatch::try_new(schema, columns).map_err(he)?;
    write_parquet_with(
        dir,
        "nulls",
        &batch,
        parquet::file::properties::WriterProperties::builder().build(),
    )
}

/// **H4** — the float edge cases the S13 clinical gate is about: `NaN` with a producer-specific
/// payload, `-0.0`, the denormal boundary, and both infinities.
///
/// The NaN payload must be canonicalised (it is uninterpreted producer noise); `-0.0` and the denormals
/// must survive bit-exactly (they are values).
fn write_floats(dir: &Path) -> Result<PathBuf> {
    let odd_nan = f64::from_bits(0x7ff8_0000_dead_beef);
    let schema = Arc::new(Schema::new(vec![field("x", DataType::Float64, false)]));
    let columns: Vec<ArrayRef> = vec![Arc::new(Float64Array::from(vec![
        odd_nan,
        -0.0,
        0.0,
        f64::INFINITY,
        f64::NEG_INFINITY,
        f64::MIN_POSITIVE,
        // The largest subnormal — the value a non-correctly-rounding parser is most likely to move.
        f64::from_bits(0x000f_ffff_ffff_ffff),
    ]))];
    let batch = RecordBatch::try_new(schema, columns).map_err(he)?;
    write_parquet_with(
        dir,
        "floats",
        &batch,
        parquet::file::properties::WriterProperties::builder().build(),
    )
}

/// The low-cardinality string table used by the dictionary pair below.
fn label_batch() -> Result<RecordBatch> {
    let schema = Arc::new(Schema::new(vec![
        field("id", DataType::Int32, false),
        field("label", DataType::Utf8, false),
    ]));
    let columns: Vec<ArrayRef> = vec![
        Arc::new(Int32Array::from(vec![1, 2, 3, 4, 5])),
        Arc::new(StringArray::from(vec![
            "zeta", "alpha", "zeta", "mu", "alpha",
        ])),
    ];
    RecordBatch::try_new(schema, columns).map_err(he)
}

/// **H9 (the dictionary half)** — the same logical table written WITH dictionary encoding.
///
/// Paired with [`write_plain_strings`]: the two fixtures must seal to the same `content_hash`, which is
/// what pins ADR-0056 §2's decision to materialise dictionaries to their *values*. The labels are
/// deliberately not in alphabetical order, so a dictionary built in first-seen order differs from one
/// built sorted — the exact difference between pandas' insertion-time `Categorical` order and another
/// writer's.
fn write_dictionary(dir: &Path) -> Result<PathBuf> {
    write_parquet_with(
        dir,
        "dictionary",
        &label_batch()?,
        parquet::file::properties::WriterProperties::builder()
            .set_dictionary_enabled(true)
            .build(),
    )
}

/// **H9 (the plain half)** — see [`write_dictionary`].
fn write_plain_strings(dir: &Path) -> Result<PathBuf> {
    write_parquet_with(
        dir,
        "plain_strings",
        &label_batch()?,
        parquet::file::properties::WriterProperties::builder()
            .set_dictionary_enabled(false)
            .build(),
    )
}

/// **H9 (the chunking half)** — the same table again, split into two-row row groups.
///
/// Must seal identically to [`write_plain_strings`]: the reader hands the canonicaliser several chunks
/// instead of one, and the fold is where nullability and dtype are resolved, so a bug there would show
/// up only under chunking.
fn write_tiny_row_groups(dir: &Path) -> Result<PathBuf> {
    write_parquet_with(
        dir,
        "tiny_row_groups",
        &label_batch()?,
        parquet::file::properties::WriterProperties::builder()
            .set_max_row_group_row_count(Some(2))
            .set_dictionary_enabled(false)
            .build(),
    )
}

/// **H9 (the container half)** — the same table as Arrow IPC.
///
/// Must seal identically to the Parquet fixtures: the container is not the product.
fn write_arrow_ipc(dir: &Path) -> Result<PathBuf> {
    let path = dir.join("scalars.arrow");
    let batch = label_batch()?;
    let file = std::fs::File::create(&path).map_err(he)?;
    let mut w = arrow_ipc::writer::FileWriter::try_new(file, &batch.schema()).map_err(he)?;
    w.write(&batch).map_err(he)?;
    w.finish().map_err(he)?;
    Ok(path)
}

/// **H3 + H8** — a CSV whose values are the float spellings a non-correctly-rounding or
/// locale-sensitive parser gets wrong.
///
/// Paired with the locale test in `csv_table.rs`: that one proves a hostile `LC_NUMERIC` changes
/// nothing; this one pins the resulting bytes, so a parser swap that changed a last-bit rounding would
/// move a golden rather than pass silently.
fn write_csv(dir: &Path) -> Result<PathBuf> {
    let path = dir.join("declared.csv");
    std::fs::write(
        &path,
        "id,x,label\n\
         1,1.5,alpha\n\
         2,0.1,beta\n\
         3,2.2250738585072011e-308,subnormal-boundary\n\
         4,8.98846567431158e307,near-max\n\
         5,0.500000000000000166533453693773481063544750213623046875,halfway\n\
         6,-0.0,negative-zero\n",
    )
    .map_err(he)?;
    Ok(path)
}

/// **H5 (the CSV half)** — declared NULL tokens plus the always-NULL empty field.
fn write_csv_nulls(dir: &Path) -> Result<PathBuf> {
    let path = dir.join("nulls.csv");
    std::fs::write(&path, "id,x\n1,1.0\n2,\n3,NA\n4,4.0\n").map_err(he)?;
    Ok(path)
}
